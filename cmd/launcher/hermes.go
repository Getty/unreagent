// hermesEntryMarker heads the mcp_servers entry hermes-setup writes, so the
// user can tell which part of the Hermes config is unreagent's and which of
// its keys a re-run refreshes.
const hermesEntryMarker = "# unreagent-managed: re-running `unreagent hermes-setup` refreshes url and headers.Authorization; other keys in this entry are kept"

// hermesWholeEntryMarker headed the entry in builds that replaced it whole
// (k96 until k116). A run puts hermesEntryMarker in its place.
const hermesWholeEntryMarker = "# unreagent-managed: re-run `unreagent hermes-setup` to refresh this entry; edits to it are overwritten"

// hermesLegacyMarker is the line releases before k96 put on top of the whole
// Hermes config. A run removes it: the marker now heads the entry only.
const hermesLegacyMarker = "# unreagent-managed: do not edit — re-run `unreagent hermes-setup` to refresh"

// localTokenComment heads the mcp.token key hermes-setup adds to
// unreagent.local.yaml.
const localTokenComment = "# Generated by `unreagent hermes-setup`: the bearer token the Hermes config\n" +
	"# sends. Keep it in this (git-ignored) file."

// hermesSetup is `unreagent hermes-setup`. It merges the unreagent MCP server
// entry into Hermes Agent's config.yaml so Hermes (Nous Research) can use the
// same toolset as Claude Code.
//
// Idempotent: a second run refreshes the keys unreagent owns in the previous
// entry instead of duplicating it. The unreagent config is **not** auto-merged
// on normal launcher runs — the user has to opt in by running this command
// once.
//
// args are the command line without the sub-command word, flags before and
// after it alike (see extractSubcommand); out receives the progress and
// summary lines.
func hermesSetup(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("hermes-setup", flag.ContinueOnError)
	cfgPath := fs.String("config", "", "Path to unreagent.yaml (default: next to the executable)")
	if err := fs.Parse(args); err != nil {
		return err
	}

	cfg, info, err := config.Load(*cfgPath)
	if err != nil {
		return err
	}

	if !cfg.Agent.Hermes.Enabled {
		fmt.Fprintln(out, "agent.hermes.enabled is not set — nothing to do.")
		fmt.Fprintln(out, "Set it in unreagent.yaml and re-run this command to integrate Hermes.")
		fmt.Fprintln(out, "Hint: this file — "+info.ConfigPath)
		return nil
	}

	// A generated token stays in memory until the Hermes merge has succeeded,
	// so a refused or unparsable Hermes config leaves unreagent.local.yaml
	// alone. Once saved there, the launcher reuses it on the next start, and
	// the bearer header Hermes sends keeps matching.
	token := cfg.MCP.Token
	tokenGenerated := false
	if token == "" {
		t, err := generateBearerToken()
		if err != nil {
			return fmt.Errorf("generate token: %w", err)
		}
		token = t
		tokenGenerated = true
	}

	hermesPath, err := resolveHermesConfigPath(cfg.Agent.Hermes.ConfigPath)
	if err != nil {
		return err
	}
	fmt.Fprintln(out, "Hermes config: "+hermesPath)

	// A dangling symlink would read as a missing config and be replaced by a
	// new one; refuse it before anything is read or written.
	if _, err := writeTarget(hermesPath); err != nil {
		return fmt.Errorf("%w (nothing written)", err)
	}

	// Read and merge first: the merge has to start from the user's config, and
	// nothing is touched if it cannot be parsed or merged.
	doc, raw, err := loadHermesYAML(hermesPath)
	if err != nil {
		return err
	}
	if err := mergeHermesServer(doc, cfg.Agent.Hermes.ServerName, cfg.MCP.ClientURL(), token); err != nil {
		return fmt.Errorf("Hermes config %s left untouched: %w", hermesPath, err)
	}
	hermesOut, err := doc.encode()
	if err == nil {
		// doc.data still holds the config as read: the entry must come out as
		// it was, with only the keys unreagent owns refreshed.
		name := cfg.Agent.Hermes.ServerName
		servers, _ := doc.data["mcp_servers"].(map[string]interface{})
		entry := hermesEntryWant(servers[name], cfg.MCP.ClientURL(), "Bearer "+token)
		err = checkEdit(doc.data, hermesOut, entry, "mcp_servers", name)
	}
	if err != nil {
		return fmt.Errorf("Hermes config %s left untouched: %w", hermesPath, err)
	}

	// The token edit is prepared before anything is written, too.
	localPath := localOverridePath(info.ConfigPath)
	var localOut []byte
	if tokenGenerated {
		if _, err := writeTarget(localPath); err != nil {
			return fmt.Errorf("%w (nothing written)", err)
		}
		if localOut, err = localConfigWithToken(localPath, token); err != nil {
			return fmt.Errorf("add the token to %s: %w (nothing written)", localPath, err)
		}
	}

	// Back up the existing file (the bytes just read) before it is replaced.
	// Empty file or not present — no backup needed.
	if len(raw) > 0 {
		bak, created, err := backupHermesConfig(hermesPath, raw)
		if err != nil {
			return fmt.Errorf("create backup: %w", err)
		}
		if created {
			fmt.Fprintln(out, "Backup: "+bak)
		} else {
			fmt.Fprintln(out, "Backup kept: "+bak)
		}
	}

	if err := os.MkdirAll(filepath.Dir(hermesPath), 0o755); err != nil {
		return fmt.Errorf("create target dir: %w", err)
	}

	// The token is saved before the Hermes config gets it, so the Hermes
	// config never carries a token the launcher does not know. If the Hermes
	// write then fails, the saved token is the first half of the setup: a
	// re-run reuses it and finishes.
	if tokenGenerated {
		was, err := writeFileAtomic(localPath, localOut, true)
		if err != nil {
			return fmt.Errorf("write token to %s: %w (Hermes config left untouched)", localPath, err)
		}
		fmt.Fprintln(out, "New bearer token generated and written to unreagent.local.yaml.")
		if was != 0 {
			fmt.Fprintf(out, "unreagent.local.yaml was open to group or others (mode %04o); tightened it to 0600, since it now holds the bearer token.\n", uint32(was))
		}
	}
	open, err := writeFileAtomic(hermesPath, hermesOut, false)
	if err != nil {
		if tokenGenerated {
			return fmt.Errorf("write Hermes config: %w (the new token is already saved in %s; re-run hermes-setup to finish)", err, localPath)
		}
		return fmt.Errorf("write Hermes config: %w", err)
	}
	// The Hermes config holds the bearer token, too, but it belongs to Hermes:
	// its mode is not changed, only named. chmod follows a symlinked path to
	// the file written, whose mode open is.
	if open != 0 {
		fmt.Fprintf(out, "The Hermes config is open to group or others (mode %04o) and holds the bearer token; it belongs to Hermes, so its mode is kept. To close it: chmod 600 %s\n", uint32(open), hermesPath)
	}

	fmt.Fprintln(out)
	fmt.Fprintln(out, "Hermes MCP server registered under mcp_servers."+cfg.Agent.Hermes.ServerName)
	fmt.Fprintln(out, "  url:    "+cfg.MCP.ClientURL())
	fmt.Fprintln(out, "  bearer: "+bearerSummary(token, tokenGenerated))
	fmt.Fprintln(out)
	fmt.Fprintln(out, "Restart Hermes so it re-reads the config. The unreagent tools")
	fmt.Fprintln(out, "(ue_start/stop/restart, logs, run_command, …) will then be available.")
	return nil
}

// resolveHermesConfigPath returns the absolute path to the Hermes config:
//   - explicitly set in agent.hermes.configPath
//   - $HERMES_HOME/config.yaml, if set
//   - otherwise ~/.hermes/config.yaml
func resolveHermesConfigPath(explicit string) (string, error) {
	if explicit != "" {
		abs, err := filepath.Abs(explicit)
		if err != nil {
			return "", fmt.Errorf("make configPath absolute: %w", err)
		}
		return filepath.ToSlash(abs), nil
	}
	if h := os.Getenv("HERMES_HOME"); h != "" {
		return filepath.ToSlash(filepath.Join(h, "config.yaml")), nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("resolve home dir: %w", err)
	}
	return filepath.ToSlash(filepath.Join(home, ".hermes", "config.yaml")), nil
}

// generateBearerToken returns 32 random bytes as a hex string (64 chars).
// Enough entropy for a localhost bearer, small enough to stay manageable in
// YAML.
func generateBearerToken() (string, error) {
	b := make([]byte, 32)
	if _, err := cryptorand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// localOverridePath returns the path to unreagent.local.yaml next to a
// unreagent.yaml (same convention as config.localPathFor).
func localOverridePath(yamlPath string) string {
	ext := filepath.Ext(yamlPath)
	return strings.TrimSuffix(yamlPath, ext) + ".local" + ext
}

// localConfigWithToken returns unreagent.local.yaml at path with mcp.token
// set to token. It edits the parsed nodes, so the file's comments, other keys
// and their order stay; a missing file starts empty. It writes nothing.
func localConfigWithToken(path, token string) ([]byte, error) {
	raw, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	doc, err := parseYAMLFile(raw)
	if err != nil {
		return nil, fmt.Errorf("not parseable: %w", err)
	}
	// The key checks come first: a token key written with a tag makes mcp
	// decode with a key that is not a string, and the message should name it.
	if err := checkMergeKeys(doc.doc); err != nil {
		return nil, err
	}
	if err := checkPlainKeys(doc.root, []string{"mcp"}, []string{"token"}); err != nil {
		return nil, err
	}
	if v := doc.data["mcp"]; v != nil {
		if _, ok := v.(map[string]interface{}); !ok {
			return nil, fmt.Errorf("mcp is not a mapping")
		}
	}
	mcp, err := childMapping(doc.root, "mcp")
	if err != nil {
		return nil, err
	}
	if key, added := setString(mcp, "token", token); added { // an empty token keeps its comments
		key.HeadComment = localTokenComment
	}
	out, err := doc.encode()
	if err != nil {
		return nil, err
	}
	if err := checkEdit(doc.data, out, token, "mcp", "token"); err != nil {
		return nil, err
	}
	return out, nil
}

// loadHermesYAML reads the Hermes config for a node edit and returns it plus
// the raw bytes it was parsed from (nil if the file does not exist). A missing
// or empty file is OK (fresh Hermes install).
func loadHermesYAML(path string) (*yamlFile, []byte, error) {
	b, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return nil, nil, fmt.Errorf("read Hermes config %s: %w", path, err)
	}
	doc, err := parseYAMLFile(b)
	if err != nil {
		return nil, nil, fmt.Errorf("Hermes config %s not parseable: %w", path, err)
	}
	return doc, b, nil
}

// yamlFile is a YAML file parsed for an edit that keeps what the edit does not
// touch: comments, key order, quoting and flow style. yaml.v3 does not keep
// blank lines or the indentation width; encode writes two spaces.
type yamlFile struct {
	// prefix is the text of a file that holds nothing but comments. yaml.v3
	// parses such a file to nothing and drops the comments, so the text is
	// kept as it is and the content goes after it.
	prefix []byte
	doc    *yaml.Node // the document node
	root   *yaml.Node // its top-level mapping
	// data is the file decoded into plain values, for the checks the nodes do
	// not answer directly: string keys, and what a merge key (<<) brings in.
	data map[string]interface{}
}

// parseYAMLFile parses raw for a node edit. An empty, comment-only or null
// file gives an empty top-level mapping; a top level that is not a mapping,
// or a duplicate key, is an error, as it is for a plain decode. So is a second
// YAML document that holds anything, even just a comment: the edit keeps only
// the first. A bare "---" or "..." at the end holds nothing and goes through.
// CRLF line breaks become LF first: yaml.v3 writes LF anyway, and it turns
// the CR of a comment line into an extra blank line.
func parseYAMLFile(raw []byte) (*yamlFile, error) {
	raw = bytes.ReplaceAll(raw, []byte("\r\n"), []byte("\n"))
	f := &yamlFile{doc: &yaml.Node{}}
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	if err := dec.Decode(f.doc); err != nil && err != io.EOF { // io.EOF: no document at all
		return nil, err
	}
	for {
		var next yaml.Node
		err := dec.Decode(&next)
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		if !config.EmptyDocument(&next) {
			return nil, fmt.Errorf("it holds more than one YAML document (another one starts at line %d); refusing to drop all but the first", next.Line)
		}
	}
	if f.doc.Kind != yaml.DocumentNode || len(f.doc.Content) == 0 {
		if len(bytes.TrimSpace(raw)) > 0 {
			f.prefix = raw
		}
		f.doc = &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{emptyMapping()}}
	}
	if err := f.doc.Decode(&f.data); err != nil {
		return nil, err
	}
	f.root = f.doc.Content[0]
	if null := f.root; null.Kind == yaml.ScalarNode && null.ShortTag() == "!!null" { // "null", "~", a bare "---"
		// The mapping takes over the comments; yaml.v3 writes no line comment
		// for a block mapping, so that one joins the head comment.
		f.root = emptyMapping()
		f.root.HeadComment = joinComments(null.HeadComment, null.LineComment)
		f.root.FootComment = null.FootComment
		f.doc.Content[0] = f.root
	}
	if f.root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("the top level is not a mapping")
	}
	return f, nil
}

// encode renders the file, the comment-only prefix first.
func (f *yamlFile) encode() ([]byte, error) {
	var b bytes.Buffer
	b.Write(f.prefix)
	if len(f.prefix) > 0 && f.prefix[len(f.prefix)-1] != '\n' {
		b.WriteByte('\n')
	}
	plainMergeKeys(f.doc)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(f.doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// plainMergeKeys clears the !!merge tag of every merge key below n. yaml.v3
// v3.0.1 writes a tagged merge key as "!!merge <<"; untagged, it writes a
// plain "<<", which every reader resolves to the same merge key.
func plainMergeKeys(n *yaml.Node) {
	if n.Kind == yaml.ScalarNode && n.ShortTag() == "!!merge" {
		n.Tag = ""
	}
	for _, c := range n.Content {
		plainMergeKeys(c)
	}
}

func emptyMapping() *yaml.Node {
	return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
}

func strNode(s string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s}
}

// mappingEntry returns the index of key's key node in m.Content, or -1.
func mappingEntry(m *yaml.Node, key string) int {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if k := m.Content[i]; k.Kind == yaml.ScalarNode && k.ShortTag() == "!!str" && k.Value == key {
			return i
		}
	}
	return -1
}

// setString sets key in the mapping m to the string s and returns the key
// node, and whether it is new. A replaced value keeps its comments; a new key
// goes at the end of m.
func setString(m *yaml.Node, key, s string) (*yaml.Node, bool) {
	value := strNode(s)
	if i := mappingEntry(m, key); i >= 0 {
		old := m.Content[i+1]
		value.HeadComment, value.LineComment, value.FootComment = old.HeadComment, old.LineComment, old.FootComment
		m.Content[i+1] = value
		return m.Content[i], false
	}
	k := strNode(key)
	m.Content = append(m.Content, k, value)
	return k, true
}

// childMapping returns the mapping under key in m: the one that is there, an
// empty one in place of a null, or an empty one under a new key at the end of
// m. An alias is an error, since adding to it would change the anchored
// mapping as well. So is a value that carries an anchor, a mapping or a null:
// adding to it would change what its aliases see, or leave them undefined.
// Any other value is an error, too. m is only changed on success.
func childMapping(m *yaml.Node, key string) (*yaml.Node, error) {
	i := mappingEntry(m, key)
	if i < 0 {
		v := emptyMapping()
		m.Content = append(m.Content, strNode(key), v)
		return v, nil
	}
	switch k, v := m.Content[i], m.Content[i+1]; {
	case v.Anchor != "":
		return nil, fmt.Errorf("%s carries the anchor &%s; adding to it would change its aliases too", key, v.Anchor)
	case v.Kind == yaml.MappingNode:
		return v, nil
	case v.Kind == yaml.ScalarNode && v.ShortTag() == "!!null":
		// yaml.v3 writes no comments of a nested block mapping, so the key
		// takes over those of the null.
		k.HeadComment = joinComments(k.HeadComment, v.HeadComment)
		k.LineComment = joinComments(k.LineComment, v.LineComment)
		k.FootComment = joinComments(k.FootComment, v.FootComment)
		m.Content[i+1] = emptyMapping()
		return m.Content[i+1], nil
	case v.Kind == yaml.AliasNode:
		return nil, fmt.Errorf("%s is an alias (*%s); adding to it would change the anchored mapping too", key, v.Value)
	default:
		return nil, fmt.Errorf("%s is not a mapping", key)
	}
}

// takeTrailingComments removes the foot comments on the last line of the
// mapping m — those of its last key and, all the way down, of its last value —
// and returns them in file order. yaml.v3 hangs a comment that follows m
// there.
func takeTrailingComments(m *yaml.Node) string {
	var parts []string
	for n := m; len(n.Content) > 0; {
		last := n.Content[len(n.Content)-1]
		if n.Kind == yaml.MappingNode {
			key := n.Content[len(n.Content)-2]
			parts = append(parts, key.FootComment)
			key.FootComment = ""
		}
		parts = append(parts, last.FootComment)
		last.FootComment = ""
		n = last
	}
	// Collected from the outside in; the innermost one comes first in the file.
	for i, j := 0, len(parts)-1; i < j; i, j = i+1, j-1 {
		parts[i], parts[j] = parts[j], parts[i]
	}
	return joinComments(parts...)
}

// anchorIn returns the name of an anchor on n or anything below it, or "".
func anchorIn(n *yaml.Node) string {
	if n.Anchor != "" {
		return n.Anchor
	}
	for _, c := range n.Content {
		if a := anchorIn(c); a != "" {
			return a
		}
	}
	return ""
}

// withoutLine returns comment without the lines that are exactly line.
func withoutLine(comment, line string) string {
	if comment == "" {
		return ""
	}
	var kept []string
	for _, l := range strings.Split(comment, "\n") {
		if strings.TrimSpace(l) != line {
			kept = append(kept, l)
		}
	}
	return strings.Join(kept, "\n")
}

// joinComments joins the non-empty comments, one per line.
func joinComments(comments ...string) string {
	var kept []string
	for _, c := range comments {
		if c != "" {
			kept = append(kept, c)
		}
	}
	return strings.Join(kept, "\n")
}

// backupHermesConfig writes raw (the config as read before the merge) to
// <path>.bak. An existing .bak is never overwritten — it may hold the user's
// original from an earlier run — so created is false when one was already
// there. A failed write removes the partial backup.
func backupHermesConfig(path string, raw []byte) (bak string, created bool, err error) {
	bak = path + ".bak"
	f, err := os.OpenFile(bak, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		if os.IsExist(err) {
			return bak, false, nil
		}
		return bak, false, err
	}
	if _, err := f.Write(raw); err != nil {
		f.Close()
		os.Remove(bak)
		return bak, false, err
	}
	if err := f.Close(); err != nil {
		os.Remove(bak)
		return bak, false, err
	}
	return bak, true, nil
}

// mergeHermesServer sets the keys unreagent owns in mcp_servers.<name> — url,
// and Authorization in headers — and heads the entry with hermesEntryMarker.
// It edits the nodes in place, so the rest of the config stays as written,
// every other key of the entry with it, other headers among them. An
// Authorization header spelled in another case is the one it sets, in that
// spelling. What is missing is added: a new entry as the last server, a new url
// first in the entry, a new headers or Authorization last in theirs. Other
// servers are left alone.
//
// What cannot be edited that way without dropping or changing more is refused,
// and doc stays unchanged: a merge key written quoted anywhere in the file
// (checkMergeKeys); a key on the way to the entry that is not written as a
// plain string (checkPlainKeys); an mcp_servers that is not a mapping with
// string keys (a list, or a key YAML reads as a number), an alias, one that
// carries an anchor (a mapping or a null), or one that comes in through a
// merge key (<<); and an entry, or its headers, that checkHermesEntry refuses.
func mergeHermesServer(doc *yamlFile, name, url, token string) error {
	if err := checkMergeKeys(doc.doc); err != nil {
		return err
	}
	if err := checkPlainKeys(doc.root, []string{"mcp_servers"}, []string{name}, []string{"headers", "url"}, []string{"Authorization"}); err != nil {
		return err
	}
	switch doc.data["mcp_servers"].(type) {
	case nil, map[string]interface{}:
	default:
		return fmt.Errorf("mcp_servers is not a mapping of server names (a list, or a key that is not a string); refusing to replace it")
	}
	if doc.data["mcp_servers"] != nil && mappingEntry(doc.root, "mcp_servers") < 0 {
		return fmt.Errorf("mcp_servers comes in through a merge key (<<); refusing to override it")
	}
	servers, err := childMapping(doc.root, "mcp_servers")
	if err != nil {
		return fmt.Errorf("%w; refusing to change it", err)
	}
	// servers is the mapping as parsed here, or a new one that holds no entry
	// to refuse, so a refusal changes nothing. Nothing below is refused.
	if err := checkHermesEntry(servers, doc.data["mcp_servers"], name); err != nil {
		return err
	}

	entry, err := childMapping(servers, name)
	if err != nil {
		return err
	}
	// When the entry is the last server, yaml.v3 hangs a comment that follows
	// it on the entry's last line. Left there, it would come before a key
	// added at the end, and the encoder indents it into the entry; on the
	// entry's key it stays after the entry. With a server after the entry, a
	// comment at the servers' indentation heads that server instead, and what
	// hangs on the entry's last line is inside the entry: it stays there.
	i := mappingEntry(servers, name)
	key := servers.Content[i]
	if i == len(servers.Content)-2 {
		key.FootComment = joinComments(key.FootComment, takeTrailingComments(entry))
	}

	if mappingEntry(entry, "url") < 0 { // a new url goes first
		entry.Content = append([]*yaml.Node{strNode("url"), strNode("")}, entry.Content...)
	}
	setString(entry, "url", url)
	headers, err := childMapping(entry, "headers")
	if err != nil {
		return err
	}
	byName, _ := doc.data["mcp_servers"].(map[string]interface{})
	old, _ := byName[name].(map[string]interface{})
	setString(headers, authorizationKey(old["headers"]), "Bearer "+token)

	// The marker of the builds that replaced the whole entry gives way, too.
	key.HeadComment = joinComments(withoutLine(withoutLine(key.HeadComment, hermesWholeEntryMarker), hermesEntryMarker), hermesEntryMarker)

	// The marker earlier releases put on top sits in the head comment of the
	// document or of its first key, or in the text of a comment-only file.
	for _, c := range []*string{&doc.doc.HeadComment, &doc.root.HeadComment, &doc.root.Content[0].HeadComment} {
		*c = withoutLine(*c, hermesLegacyMarker)
	}
	if p := withoutLine(string(doc.prefix), hermesLegacyMarker); strings.TrimSpace(p) != "" {
		doc.prefix = []byte(p)
	} else {
		doc.prefix = nil
	}
	return nil
}

// checkMergeKeys refuses a merge key below n that is written quoted (or as a
// block scalar) with the !!merge tag, such as !!merge "<<". yaml.v3 reads it
// as a merge key, but encode clears the tag (plainMergeKeys), and a quoted
// "<<" without one is a plain string key to every reader: the merge would be
// lost. The first one in the file is named by its line.
func checkMergeKeys(n *yaml.Node) error {
	if n.Kind == yaml.ScalarNode && n.ShortTag() == "!!merge" && n.Value == "<<" &&
		n.Style&(yaml.SingleQuotedStyle|yaml.DoubleQuotedStyle|yaml.LiteralStyle|yaml.FoldedStyle) != 0 {
		return fmt.Errorf("the merge key at line %d is written quoted with the !!merge tag (!!merge \"<<\"); the YAML writer would turn it into a plain string key \"<<\" that merges nothing; write it unquoted as <<, then re-run hermes-setup", n.Line)
	}
	for _, c := range n.Content {
		if err := checkMergeKeys(c); err != nil {
			return err
		}
	}
	return nil
}

// checkPlainKeys refuses a key on the way to what an edit sets that reads as
// one of the keys it looks for but is not written as a plain string: an alias
// (*u) or a tag (!!binary dXJs). levels holds the keys looked for in root, in
// the mapping under the first of them, and so on down; Authorization matches
// in any case, as header names do. The node edit finds keys by their plain
// spelling, so it would add a second one beside it; and another YAML reader
// may not read it as that name at all (Python reads !!binary as bytes). Merge
// keys are left to the checks that follow.
func checkPlainKeys(root *yaml.Node, levels ...[]string) error {
	m, where := root, ""
	for _, keys := range levels {
		for i := 0; i+1 < len(m.Content); i += 2 {
			k := m.Content[i]
			if k.Kind == yaml.ScalarNode && (k.ShortTag() == "!!str" || k.ShortTag() == "!!merge") {
				continue
			}
			var v interface{}
			if k.Decode(&v) != nil {
				continue
			}
			s, _ := v.(string)
			for _, key := range keys {
				if s == key || key == "Authorization" && strings.EqualFold(s, key) {
					form := "*" + k.Value
					if k.Kind != yaml.AliasNode {
						form = k.ShortTag() + " " + k.Value
					}
					return fmt.Errorf("the key %s%s is written as %s, not as a plain string; hermes-setup would add a second %s instead of changing it; write the key as plain %s, then re-run hermes-setup", where, s, form, s, s)
				}
			}
		}
		i := mappingEntry(m, keys[0])
		if i < 0 || m.Content[i+1].Kind != yaml.MappingNode {
			return nil
		}
		m, where = m.Content[i+1], where+keys[0]+"."
	}
	return nil
}

// checkHermesEntry refuses an entry mcp_servers.<name> that mergeHermesServer
// cannot edit in place without changing more than the keys it owns. servers is
// the mcp_servers mapping, data what it decodes to. The entry and its headers
// are refused if they decode to anything but a mapping with string keys (a
// list, a single value, or a key YAML reads as a number), come in through a
// merge key (<<), which a key of the entry's own would hide whole, or are an
// alias, since the edit would change the anchored mapping. So is an entry that
// carries an anchor, on itself or below: the edit would change what its
// aliases see, or leave them undefined. And so is an entry that is a stdio
// server (it has a command), which is the user's own, and one whose headers
// spell Authorization more than one way: header names ignore case, so which
// token counts is ambiguous. Those two are read from data, so a command or a
// header that comes in through a merge key counts, too.
func checkHermesEntry(servers *yaml.Node, data interface{}, name string) error {
	byName, _ := data.(map[string]interface{})
	if entry, ok := byName[name].(map[string]interface{}); ok {
		where := "mcp_servers." + name
		if _, stdio := entry["command"]; stdio {
			return fmt.Errorf("%s is a stdio server (it sets command), and hermes-setup only manages an HTTP entry (url and headers); remove command and args from the entry, or rename or delete the entry, then re-run hermes-setup", where)
		}
		if keys := authorizationKeys(entry["headers"]); len(keys) > 1 {
			return fmt.Errorf("%s.headers sets the Authorization header more than once (%s); header names ignore case, so which token counts is ambiguous; keep one, then re-run hermes-setup", where, strings.Join(keys, ", "))
		}
	}

	m, where := servers, "mcp_servers"
	for _, key := range []string{name, "headers"} {
		where += "." + key
		d, _ := data.(map[string]interface{})
		switch d[key].(type) {
		case nil, map[string]interface{}:
		default:
			return fmt.Errorf("%s is not a mapping with string keys (a list, a single value, or a key that is not a string); refusing to change it", where)
		}
		i := mappingEntry(m, key)
		if i < 0 {
			if d[key] != nil {
				return fmt.Errorf("%s comes in through a merge key (<<); refusing to override it", where)
			}
			return nil // nothing there, nothing below
		}
		v := m.Content[i+1]
		if a := anchorIn(v); a != "" {
			return fmt.Errorf("%s carries the anchor &%s, which other parts of the config may use; refusing to change it", where, a)
		}
		if v.Kind == yaml.AliasNode {
			return fmt.Errorf("%s is an alias (*%s); adding to it would change the anchored mapping too; refusing to change it", where, v.Value)
		}
		m, data = v, d[key] // a null has no keys: the next round finds nothing
	}
	return nil
}

// hermesEntryWant returns what mergeHermesServer leaves at mcp_servers.<name>,
// decoded: old, the entry as decoded before the edit (nil for none), with the
// keys unreagent owns set — url, and Authorization in headers, under the
// spelling authorizationKey picks. old is not changed.
func hermesEntryWant(old interface{}, url, bearer string) map[string]interface{} {
	entry := map[string]interface{}{}
	if m, ok := old.(map[string]interface{}); ok {
		for k, v := range m {
			entry[k] = v
		}
	}
	headers := map[string]interface{}{}
	if m, ok := entry["headers"].(map[string]interface{}); ok {
		for k, v := range m {
			headers[k] = v
		}
	}
	headers[authorizationKey(headers)] = bearer
	entry["url"] = url
	entry["headers"] = headers
	return entry
}

// authorizationKeys returns the keys of headers, as decoded, that name the
// Authorization header, sorted. HTTP header names ignore case.
func authorizationKeys(headers interface{}) []string {
	h, _ := headers.(map[string]interface{})
	var keys []string
	for k := range h {
		if strings.EqualFold(k, "Authorization") {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	return keys
}

// authorizationKey returns the key the bearer goes under in headers, as
// decoded: the one key that names the Authorization header, in its spelling,
// or "Authorization" if none does. checkHermesEntry refuses more than one.
func authorizationKey(headers interface{}) string {
	if keys := authorizationKeys(headers); len(keys) == 1 {
		return keys[0]
	}
	return "Authorization"
}

// checkEdit is the safety net between encoding an edit and writing it: out
// must parse, hold want at path, and hold everything else as before did. It
// catches what the node edit and yaml.v3's encoder could break unnoticed, such
// as an alias left without its anchor. A change outside path is named by where
// it is (changedPath), with the fix the user can make by hand, and so is one
// inside it, below a want that is a mapping or a list.
func checkEdit(before map[string]interface{}, out []byte, want interface{}, path ...string) error {
	var after map[string]interface{}
	if err := yaml.Unmarshal(out, &after); err != nil {
		return fmt.Errorf("the result would not parse: %w", err)
	}
	where := strings.Join(path, ".")
	var got interface{} = after
	for _, k := range path {
		m, _ := got.(map[string]interface{})
		got = m[k]
	}
	if !sameValue(got, want) {
		// The values the edit sets are new plain string nodes, which the
		// encoder writes back as they are, so a value that differs at path
		// is one of the user's, kept as parsed, that the encoder writes back
		// differently (see below).
		if changedPath(want, got) != "" {
			return reencoded("the result would not hold the new "+where, pathTo(where, want, got))
		}
		return fmt.Errorf("the result would not hold the new %s", where)
	}
	if old, rest := withoutPath(before, path...), withoutPath(after, path...); !sameValue(old, rest) {
		// The node edit leaves every other value as it was parsed, so what
		// differs is a value yaml.v3 writes back differently: v3.0.1 adds a
		// blank line to a folded block scalar with a more-indented line, and
		// drops the leading blank line of a literal one.
		if at := changedPath(old, rest); at != "" {
			return reencoded("the result would change more than "+where, at)
		}
		return fmt.Errorf("the result would change more than %s", where)
	}
	return nil
}

// reencoded is checkEdit's refusal of a value the YAML writer would write back
// differently: what goes wrong, then the path to the value and the fix.
func reencoded(what, at string) error {
	return fmt.Errorf("%s: the value at %s would change (the YAML writer re-encodes it differently, e.g. a block scalar); rewrite that value as a quoted string, or as a block scalar without a leading blank line or extra-indented lines, then re-run hermes-setup", what, at)
}

// changedPath returns the path to the first value that differs between a and
// b, both decoded YAML: keys joined by dots, list indexes in brackets
// (mcp_servers.github.args[1]), map keys taken in sorted order. The path ends
// at a key only one of them has, at values of different kinds, and at lists
// of different lengths. It is "" when a and b are the same, and when they
// differ but are not both mappings or both lists of the same length.
func changedPath(a, b interface{}) string {
	if ma, ok := asMapping(a); ok {
		mb, ok := asMapping(b)
		if !ok {
			return ""
		}
		var keys []interface{}
		for k := range ma {
			keys = append(keys, k)
		}
		for k := range mb {
			if _, ok := ma[k]; !ok {
				keys = append(keys, k)
			}
		}
		sort.Slice(keys, func(i, j int) bool { return fmt.Sprint(keys[i]) < fmt.Sprint(keys[j]) })
		for _, k := range keys {
			va, inA := ma[k]
			vb, inB := mb[k]
			switch {
			case inA && inB && sameValue(va, vb):
			case inA && inB:
				return pathTo(fmt.Sprint(k), va, vb)
			default:
				return fmt.Sprint(k)
			}
		}
		return ""
	}
	la, okA := a.([]interface{})
	lb, okB := b.([]interface{})
	if !okA || !okB || len(la) != len(lb) {
		return ""
	}
	for i := range la {
		if !sameValue(la[i], lb[i]) {
			return pathTo(fmt.Sprintf("[%d]", i), la[i], lb[i])
		}
	}
	return ""
}

// pathTo returns head, the key or index of a and b, followed by changedPath
// below it: a key after a dot, an index as it is.
func pathTo(head string, a, b interface{}) string {
	below := changedPath(a, b)
	if below != "" && !strings.HasPrefix(below, "[") {
		below = "." + below
	}
	return head + below
}

// asMapping returns a decoded YAML mapping, whichever map type yaml.v3 chose
// for it, keyed by interface{}.
func asMapping(v interface{}) (map[interface{}]interface{}, bool) {
	switch v := v.(type) {
	case map[interface{}]interface{}:
		return v, true
	case map[string]interface{}:
		m := make(map[interface{}]interface{}, len(v))
		for k, e := range v {
			m[k] = e
		}
		return m, true
	}
	return nil, false
}

// sameValue is reflect.DeepEqual for decoded YAML, except that NaN equals
// NaN: a .nan in the file is the same value before and after the edit, but
// never equal to itself as a float.
func sameValue(a, b interface{}) bool {
	switch a := a.(type) {
	case float64:
		b, ok := b.(float64)
		return ok && (a == b || math.IsNaN(a) && math.IsNaN(b))
	case []interface{}:
		b, ok := b.([]interface{})
		if !ok || len(a) != len(b) {
			return false
		}
		for i := range a {
			if !sameValue(a[i], b[i]) {
				return false
			}
		}
		return true
	case map[string]interface{}:
		b, ok := b.(map[string]interface{})
		if !ok || len(a) != len(b) {
			return false
		}
		for k, v := range a {
			if w, ok := b[k]; !ok || !sameValue(v, w) {
				return false
			}
		}
		return true
	case map[interface{}]interface{}:
		b, ok := b.(map[interface{}]interface{})
		if !ok || len(a) != len(b) {
			return false
		}
		for k, v := range a {
			if w, ok := b[k]; !ok || !sameValue(v, w) {
				return false
			}
		}
		return true
	default:
		return reflect.DeepEqual(a, b)
	}
}

// withoutPath returns a copy of data without the value at path. A parent map
// that is null or ends up empty is dropped as well, so a new mcp_servers that
// holds only the edit compares equal to none. data is not changed.
func withoutPath(data map[string]interface{}, path ...string) map[string]interface{} {
	out := make(map[string]interface{}, len(data))
	for k, v := range data {
		out[k] = v
	}
	if len(path) == 0 {
		return out
	}
	k := path[0]
	if len(path) == 1 {
		delete(out, k)
		return out
	}
	child, isMap := out[k].(map[string]interface{})
	if !isMap && out[k] != nil {
		return out // not a map: nothing below it to drop
	}
	if rest := withoutPath(child, path[1:]...); len(rest) > 0 {
		out[k] = rest
	} else {
		delete(out, k)
	}
	return out
}

// bearerSummary describes the bearer token for the setup summary. Only a
// token this command generated is known to be 64 hex chars and to live in
// unreagent.local.yaml, so only that one gets the claim and an eight-character
// prefix. A token the user set in mcp.token can have any length and is not
// echoed: a prefix of a short one is most of the secret.
func bearerSummary(token string, generated bool) string {
	if !generated {
		return fmt.Sprintf("mcp.token from your unreagent config (%d chars, not shown)", len(token))
	}
	return token[:min(8, len(token))] + "… (64 hex chars, in unreagent.local.yaml)"
}

// writeTarget returns the file a write to path replaces: the target of a
// symlinked file, or path itself. Only a symlinked file is resolved: a path
// through a symlinked directory stays as given, so errors name the directory
// the user knows, and the rename lands in the real directory either way. A
// dangling symlink is refused: the real file usually lives somewhere that is
// unavailable right now, and writing would replace the link with a new file
// that holds none of it. So is a link that cannot be resolved at all, such as
// a loop. Every error names path (config.ResolveLink).
func writeTarget(path string) (string, error) {
	target, err := config.ResolveLink(path)
	if errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("%w; refusing to replace the link with a new file", err)
	}
	return target, err
}

// writeFileAtomic writes data to path safely: to a temp file
// <name>.tmp-<random> in the same directory, synced to disk, then renamed over
// path, so a kill mid-write leaves the old file whole. A symlinked file is
// followed and its target replaced, so the link stays a link; a dangling one
// is refused (see writeTarget). A replaced file keeps its permission bits; a
// new one gets 0600, since it may hold a token. The mode of a replaced file
// whose bits let group or others at it is returned, 0 when they do not (a new
// file never does). secret says that data holds a token: such a file then
// gets 0600 instead of its bits. The temp file gets the final mode before the
// rename, so the secret is never on disk under the old bits. On Windows the
// bits do not decide who can read the file (it inherits its directory's ACL),
// so nothing is tightened or returned there. The directory must be writable
// for the temp file; there is no in-place fallback.
func writeFileAtomic(path string, data []byte, secret bool) (os.FileMode, error) {
	path, err := writeTarget(path)
	if err != nil {
		return 0, err
	}
	mode, open := os.FileMode(0o600), os.FileMode(0)
	if fi, err := os.Stat(path); err == nil {
		mode = fi.Mode().Perm()
	}
	if runtime.GOOS != "windows" && mode&0o077 != 0 {
		open = mode
		if secret {
			mode = 0o600
		}
	}
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, filepath.Base(path)+".tmp-*")
	if err != nil {
		return 0, fmt.Errorf("create a temp file in directory %s: %w", dir, err)
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName) // in case a step below fails

	_, err = tmp.Write(data)
	if err == nil {
		err = tmp.Chmod(mode)
	}
	if err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return 0, err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return 0, err
	}
	return open, nil
}
